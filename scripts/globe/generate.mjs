// Builds src/components/story/land.ts: evenly spread points on the globe that fall on land.
// Source: Natural Earth 1:110m land polygons (public domain), from
//   https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_land.geojson
// Run: node scripts/globe/generate.mjs path/to/ne_110m_land.geojson
import fs from "node:fs";

const file = process.argv[2];
if (!file) {
  console.error("usage: node scripts/globe/generate.mjs <ne_110m_land.geojson>");
  process.exit(1);
}
const geo = JSON.parse(fs.readFileSync(file, "utf8"));

// every outer ring and hole, as [lon, lat] lists, with a bounding box for a quick reject
const rings = [];
for (const f of geo.features) {
  const polys = f.geometry.type === "Polygon" ? [f.geometry.coordinates] : f.geometry.coordinates;
  for (const poly of polys) {
    for (const ring of poly) {
      let x0 = Infinity, x1 = -Infinity, y0 = Infinity, y1 = -Infinity;
      for (const [x, y] of ring) {
        x0 = Math.min(x0, x); x1 = Math.max(x1, x);
        y0 = Math.min(y0, y); y1 = Math.max(y1, y);
      }
      rings.push({ ring, box: [x0, x1, y0, y1] });
    }
  }
}

// even-odd rule across all rings: holes cancel their outer ring
function onLand(lon, lat) {
  let inside = false;
  for (const { ring, box } of rings) {
    if (lon < box[0] || lon > box[1] || lat < box[2] || lat > box[3]) continue;
    for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
      const [xi, yi] = ring[i], [xj, yj] = ring[j];
      if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) inside = !inside;
    }
  }
  return inside;
}

// Fibonacci sphere: the same spacing everywhere, so the dots read as a texture rather than a grid
const N = 16000;
const golden = Math.PI * (3 - Math.sqrt(5));
const out = [];
for (let i = 0; i < N; i++) {
  const y = 1 - (i / (N - 1)) * 2;
  const lat = (Math.asin(y) * 180) / Math.PI;
  const lon = ((((i * golden * 180) / Math.PI) % 360) + 540) % 360 - 180;
  if (lat < -62) continue; // Antarctica would only crowd the bottom of the view
  if (onLand(lon, lat)) out.push(Math.round(lat * 10), Math.round(lon * 10));
}

const body = `// Generated by scripts/globe/generate.mjs from Natural Earth 1:110m land (public domain). Do not edit.
// Pairs of [latitude, longitude] in tenths of a degree.
export const LAND = new Int16Array([${out.join(",")}]);
`;
fs.writeFileSync(new URL("../../src/components/story/land.ts", import.meta.url), body);
console.log(`${out.length / 2} land points`);
