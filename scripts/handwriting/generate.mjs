// Builds src/components/hero/handwriting.ts from the single-stroke Hershey Script font.
// Source: HersheyScript1.svg from Inkscape's svg_fonts (Hershey fonts, Dr. A. V. Hershey, U.S. NBS, public domain).
// Run: node scripts/handwriting/generate.mjs
import fs from "node:fs";

const src = fs.readFileSync(new URL("./HersheyScript1.svg", import.meta.url), "utf8");
const glyphs = {};
for (const m of src.matchAll(/<glyph([^>]*)\/?>/g)) {
  const u = m[1].match(/unicode="([^"]*)"/)?.[1];
  if (u === undefined) continue;
  glyphs[u] = { adv: +(m[1].match(/horiz-adv-x="([-\d.]+)"/)?.[1] ?? 500), d: m[1].match(/ d="([^"]*)"/)?.[1] ?? "" };
}

function polylines(d) {
  const out = [];
  let cur = null, cmd = "M";
  const t = d.match(/[ML]|-?[\d.]+(?:e-?\d+)?/g) ?? [];
  for (let i = 0; i < t.length; ) {
    if (t[i] === "M" || t[i] === "L") { cmd = t[i++]; continue; }
    const p = [+t[i++], -t[i++]]; // flip y: font units are y-up
    if (cmd === "M") { cur = [p]; out.push(cur); cmd = "L"; } else cur.push(p);
  }
  return out;
}

// Catmull-Rom through the plotter points -> smooth cubic Béziers, so the pen glides instead of zig-zagging.
function smooth(pts, tension = 0.5) {
  const f = (n) => +n.toFixed(1);
  if (pts.length < 3) return `M${pts.map((p) => p.map(f).join(" ")).join(" L")}`;
  let d = `M${f(pts[0][0])} ${f(pts[0][1])}`;
  for (let i = 0; i < pts.length - 1; i++) {
    const p0 = pts[i - 1] ?? pts[i], p1 = pts[i], p2 = pts[i + 1], p3 = pts[i + 2] ?? p2;
    const c1 = [p1[0] + ((p2[0] - p0[0]) * tension) / 3, p1[1] + ((p2[1] - p0[1]) * tension) / 3];
    const c2 = [p2[0] - ((p3[0] - p1[0]) * tension) / 3, p2[1] - ((p3[1] - p1[1]) * tension) / 3];
    d += ` C${f(c1[0])} ${f(c1[1])} ${f(c2[0])} ${f(c2[1])} ${f(p2[0])} ${f(p2[1])}`;
  }
  return d;
}

function word(text) {
  let x = 0;
  const strokes = [];
  for (const ch of text) {
    const g = glyphs[ch];
    for (const s of polylines(g.d)) strokes.push(s.map(([a, b]) => [a + x, b]));
    x += g.adv;
  }
  const xs = strokes.flat().map((p) => p[0]), ys = strokes.flat().map((p) => p[1]);
  const pad = 40;
  const box = [Math.min(...xs) - pad, Math.min(...ys) - pad, Math.max(...xs) - Math.min(...xs) + pad * 2, Math.max(...ys) - Math.min(...ys) + pad * 2].map((n) => +n.toFixed(1));
  // baseline sits at y = 0 in font units; keep it so both words can share one baseline
  return { viewBox: box, paths: strokes.map((s) => smooth(s)) };
}

const data = { reynard: word("Reynard") };
const out = `// Generated by scripts/handwriting/generate.mjs from Hershey Script (public domain). Do not edit by hand.
// Coordinates are font units, y down, baseline at y = 0.
export type Handwriting = { viewBox: [number, number, number, number]; paths: string[] };

export const handwriting: Record<"reynard", Handwriting> = ${JSON.stringify(data)};
`;
fs.writeFileSync(new URL("../../src/components/hero/handwriting.ts", import.meta.url), out);
console.log("reynard", data.reynard.paths.length, "strokes", data.reynard.viewBox);
